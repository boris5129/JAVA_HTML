_BLOCKS = [m.group(1) for m in re.finditer(r"```sql(?: run| error)?[^\n]*\n(.*?)```", _SRC, re.S)]


def B(key):
    """교안 SQL 블록 중 key를 포함하는 첫 블록 (DB 이름 치환)"""
    for b in _BLOCKS:
        if key in b:
            return b.rstrip().replace("{{DB}}", "hanip_delivery12")
    raise KeyError(key)


def lines(sql, start, end=None, exact=False):
    """sql에서 start를 포함하는 줄부터 end를 포함하는(exact면 정확히 같은) 줄까지 (표시용 발췌)"""
    ls = sql.splitlines()
    i = next(k for k, l in enumerate(ls) if start in l)
    hit = (lambda l: l.rstrip() == end) if exact else (lambda l: end in l)
    j = next(k for k, l in enumerate(ls) if k >= i and hit(l)) if end else len(ls) - 1
    return "\n".join(ls[i:j + 1])


def head(block):
    """'… DELIMITER ;' 까지 (생성 부분)"""
    return block.split("DELIMITER ;")[0] + "DELIMITER ;"


def tail(block):
    """'DELIMITER ;' 뒤 (실행 부분)"""
    return block.split("DELIMITER ;", 1)[1].strip()


